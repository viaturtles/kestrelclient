// ---------------- Mission Control events ----------------

#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct MissionEvent {
    pub kind: String, // reset | step | log | state
    pub step: Option<String>,
    pub status: Option<String>, // pending | running | done | failed | skipped
    pub label: Option<String>,
    pub detail: Option<String>,
    pub level: Option<String>, // info | warn | error | game
    pub line: Option<String>,
    pub time: String,
}

impl MissionEvent {
    fn base(kind: &str) -> Self {
        Self { kind: kind.into(), step: None, status: None, label: None, detail: None, level: None, line: None, time: now_hms() }
    }
}

pub fn mission(app: &AppHandle, state: &AppState, ev: MissionEvent) {
    {
        let mut buf = state.mission.lock().unwrap();
        if ev.kind == "reset" { buf.clear(); }
        buf.push(ev.clone());
        if buf.len() > 5000 { let cut = buf.len() - 5000; buf.drain(0..cut); }
    }
    if let Some(l) = &ev.line { write_log(state, l); }
    // Per-launch history file (logs\launches\<time>.log), one JSON event per line.
    if ev.kind == "reset" {
        let secs = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0);
        let dir = logs_dir().join("launches");
        let _ = std::fs::create_dir_all(&dir);
        *state.launch_log.lock().unwrap() = Some(dir.join(format!("{secs}.log")));
        // Keep the 30 most recent launches.
        if let Ok(rd) = std::fs::read_dir(&dir) {
            let mut files: Vec<_> = rd.flatten().map(|e| e.path()).collect();
            files.sort();
            if files.len() > 30 { for f in &files[..files.len() - 30] { let _ = std::fs::remove_file(f); } }
        }
    }
    if let Some(p) = state.launch_log.lock().unwrap().as_ref() {
        if let Ok(mut f) = std::fs::OpenOptions::new().create(true).append(true).open(p) {
            let _ = writeln!(f, "{}", serde_json::to_string(&ev).unwrap_or_default());
        }
    }
    let _ = app.emit("kestrel://mission", ev);
}

pub fn m_reset(app: &AppHandle, state: &AppState, title: &str) {
    let mut e = MissionEvent::base("reset");
    e.label = Some(title.into());
    mission(app, state, e);
}
pub fn m_step(app: &AppHandle, state: &AppState, step: &str, status: &str, label: &str, detail: &str) {
    let mut e = MissionEvent::base("step");
    e.step = Some(step.into()); e.status = Some(status.into()); e.label = Some(label.into()); e.detail = Some(detail.into());
    mission(app, state, e);
}
pub fn m_log(app: &AppHandle, state: &AppState, level: &str, line: &str) {
    let mut e = MissionEvent::base("log");
    e.level = Some(level.into()); e.line = Some(line.into());
    mission(app, state, e);
}
pub fn m_state(app: &AppHandle, state: &AppState, st: &str, detail: &str) {
    m_state_fix(app, state, st, detail, "");
}
/// A state with a one-click fix id for Launch Control (in `label`; see launch::explain_crash).
pub fn m_state_fix(app: &AppHandle, state: &AppState, st: &str, detail: &str, fix: &str) {
    let mut e = MissionEvent::base("state");
    e.status = Some(st.into()); e.detail = Some(detail.into());
    if !fix.is_empty() { e.label = Some(fix.into()); }
    mission(app, state, e);
}
