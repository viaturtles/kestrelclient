pub type Res<T> = Result<T, String>;

pub fn err<E: std::fmt::Display>(context: &str) -> impl FnOnce(E) -> String + '_ {
    move |e| format!("{context}: {e}")
}

pub const USER_AGENT: &str = "kestrel-launcher/0.1.0 (private build; github.com/turtles)";

/// Everything Kestrel stores lives in %APPDATA%\Kestrel.
pub fn data_dir() -> PathBuf {
    let base = std::env::var_os("APPDATA")
        .map(PathBuf::from)
        .unwrap_or_else(|| std::env::temp_dir());
    base.join("Kestrel")
}
pub fn instances_dir() -> PathBuf { data_dir().join("instances") }
pub fn versions_dir() -> PathBuf { data_dir().join("versions") }
pub fn libraries_dir() -> PathBuf { data_dir().join("libraries") }
pub fn assets_dir() -> PathBuf { data_dir().join("assets") }
pub fn runtime_dir() -> PathBuf { data_dir().join("runtime") }
pub fn logs_dir() -> PathBuf { data_dir().join("logs") }

/// Instance ids are generated by the launcher: lowercase letters, digits and dashes only.
pub fn safe_id(id: &str) -> Res<&str> {
    if !id.is_empty() && id.len() <= 64 && id.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-') {
        Ok(id)
    } else {
        Err("Invalid installation id".into())
    }
}

/// A single file name inside a known folder; never a path.
pub fn safe_file_name(name: &str) -> Res<&str> {
    if name.is_empty() || name.contains(['/', '\\', ':']) || name == "." || name == ".." || name.starts_with("..") {
        Err("Invalid file name".into())
    } else {
        Ok(name)
    }
}

/// True when `path` is inside Kestrel's data folder.
pub fn inside_data_dir(path: &Path) -> bool {
    let root = data_dir();
    match (path.canonicalize(), root.canonicalize()) {
        (Ok(p), Ok(r)) => p.starts_with(r),
        _ => false,
    }
}

pub struct GameProcess {
    pub child: tokio::process::Child,
    pub instance_id: String,
}

pub struct AppState {
    pub http: reqwest::Client,
    pub cancels: Mutex<HashMap<String, Arc<AtomicBool>>>,
    pub game: tokio::sync::Mutex<Option<GameProcess>>,
    pub mission: Mutex<Vec<MissionEvent>>,
    pub log_lock: Mutex<()>,
    pub launch_log: Mutex<Option<PathBuf>>,
    pub discord: crate::discord::Discord,
    pub last_launch: Mutex<Option<crate::launch::LaunchRequest>>,
}

impl AppState {
    pub fn new() -> Self {
        let http = reqwest::Client::builder()
            .user_agent(USER_AGENT)
            .connect_timeout(std::time::Duration::from_secs(10))
            .timeout(std::time::Duration::from_secs(120))
            .build()
            .expect("HTTP client");
        Self {
            http,
            cancels: Mutex::new(HashMap::new()),
            game: tokio::sync::Mutex::new(None),
            mission: Mutex::new(Vec::new()),
            log_lock: Mutex::new(()),
            launch_log: Mutex::new(None),
            discord: crate::discord::Discord::start(crate::config::load().discord_app_id),
            last_launch: Mutex::new(None),
        }
    }
}

/// Appends a line to %APPDATA%\Kestrel\logs\launcher.log. Never contains tokens.
/// Settings → Storage → "Keep logs for": starts a new launcher.log each day (the old one is kept as
/// launcher-<unix secs>.log) and deletes logs and launch records older than `days` (None = forever).
#[tauri::command]
pub fn cleanup_logs(state: tauri::State<'_, AppState>, days: Option<u32>) -> Res<u32> {
    let _g = state.log_lock.lock();
    let dir = logs_dir();
    let now = std::time::SystemTime::now();
    let age_days = |p: &std::path::Path| p.metadata().and_then(|m| m.modified()).ok().and_then(|t| now.duration_since(t).ok()).map(|d| d.as_secs() / 86400);
    let main = dir.join("launcher.log");
    if age_days(&main).map(|d| d >= 1).unwrap_or(false) {
        let secs = now.duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0);
        let _ = std::fs::rename(&main, dir.join(format!("launcher-{secs}.log")));
    }
    let Some(days) = days else { return Ok(0) };
    let mut removed = 0;
    for folder in [dir.clone(), dir.join("launches")] {
        let Ok(rd) = std::fs::read_dir(&folder) else { continue };
        for e in rd.flatten() {
            let p = e.path();
            if !p.is_file() || p == main || p.extension().map(|x| x != "log").unwrap_or(true) { continue; }
            if age_days(&p).map(|d| d >= days as u64).unwrap_or(false) && std::fs::remove_file(&p).is_ok() { removed += 1; }
        }
    }
    Ok(removed)
}

pub fn write_log(state: &AppState, line: &str) {
    let _g = state.log_lock.lock();
    let dir = logs_dir();
    let _ = std::fs::create_dir_all(&dir);
    if let Ok(mut f) = std::fs::OpenOptions::new().create(true).append(true).open(dir.join("launcher.log")) {
        let _ = writeln!(f, "[{}] {}", now_hms(), line);
    }
}

pub fn now_hms() -> String {
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    // Local offset is not available without extra crates; logs use UTC.
    format!("{:02}:{:02}:{:02}Z", (secs / 3600) % 24, (secs / 60) % 60, secs % 60)
}

